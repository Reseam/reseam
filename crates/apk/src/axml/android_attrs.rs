#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_agrees_with_the_named_constants() {
        assert!(ANDROID_ATTRS.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for (name, id) in [
            ("label", ATTR_LABEL),
            ("icon", ATTR_ICON),
            ("drawable", ATTR_DRAWABLE),
            ("name", ATTR_NAME),
            ("enabled", ATTR_ENABLED),
            ("configChanges", ATTR_CONFIG_CHANGES),
            ("mimeType", ATTR_MIME_TYPE),
            ("targetActivity", ATTR_TARGET_ACTIVITY),
            ("minSdkVersion", ATTR_MIN_SDK_VERSION),
            ("versionCode", ATTR_VERSION_CODE),
            ("versionName", ATTR_VERSION_NAME),
            ("splitName", ATTR_SPLIT_NAME),
        ] {
            assert_eq!(android_attr_res_id(name), Some(id), "{name}");
        }
        assert_eq!(android_attr_res_id("notAnAttribute"), None);
    }

    #[test]
    fn framework_resources_resolve_by_type_and_name() {
        assert!(ANDROID_RESOURCES
            .windows(2)
            .all(|pair| (pair[0].0, pair[0].1) < (pair[1].0, pair[1].1)));
        assert_eq!(android_res_id("color", "white"), Some(0x0106_000b));
        assert_eq!(android_res_id("style", "Theme.Material"), Some(0x0103_0224));
        assert_eq!(android_res_id("attr", "label"), Some(ATTR_LABEL));
        assert_eq!(android_res_id("color", "notAColor"), None);
    }

    #[test]
    fn framework_attribute_symbols_carry_their_kind() {
        assert!(ANDROID_ATTR_SYMBOLS
            .windows(2)
            .all(|pair| (pair[0].0, pair[0].1) < (pair[1].0, pair[1].1)));
        assert!(ANDROID_FLAG_ATTRS.windows(2).all(|pair| pair[0] < pair[1]));
        let scale_type = android_attr_res_id("scaleType").unwrap();
        let gravity = android_attr_res_id("gravity").unwrap();
        assert_eq!(
            android_attr_symbol(scale_type, "center"),
            Some(AttrSymbol {
                value: 5,
                flags: false
            })
        );
        assert_eq!(
            android_attr_symbol(gravity, "center_vertical"),
            Some(AttrSymbol {
                value: 0x10,
                flags: true
            })
        );
        assert_eq!(android_attr_symbol(scale_type, "center_vertical"), None);
    }
}
