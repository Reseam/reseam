package app.reseam.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

private val EXT_JS_MODULE_MEMBERS = setOf("name", "export", "toString")

/** Generates an `ExtJsModule` binding for each JavaScript extension from its exports. */
internal abstract class JavascriptBindingsTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val exports: ConfigurableFileCollection

    @get:Input abstract val packageName: Property<String>
    @get:OutputDirectory abstract val output: DirectoryProperty

    @TaskAction
    fun run() {
        val directory =
            output.get().asFile.also(::recreate).resolve(packageName.get().replace('.', '/'))
        directory.mkdirs()
        for (file in exports) {
            val extension = bundleJson.decodeFromString<JavascriptExports>(file.readText())
            extension.exports
                .firstOrNull { it in EXT_JS_MODULE_MEMBERS }
                ?.let {
                    throw GradleException(
                        "${extension.artifact} exports $it, a name ExtJsModule uses"
                    )
                }
            val writer = KotlinWriter()
            writer.line(
                "// Generated by the Reseam Gradle plugin from a JavaScript extension's exports."
            )
            writer.line("package ${packageName.get()}")
            writer.line()
            writer.line("import app.reseam.patch.ExtJsModule")
            writer.line()
            writer.block(
                "object ${kotlinName(extension.binding)} : ExtJsModule(${kotlinString(extension.artifact)})"
            ) {
                extension.exports.forEach { line(declaration(extension.artifact, it)) }
            }
            val properties = extension.exports.groupBy { kotlinName(it) }
            properties.entries
                .firstOrNull { it.value.size > 1 }
                ?.let { (property, names) ->
                    throw GradleException(
                        "${extension.artifact} exports ${names.joinToString(" and ")}, which bind to one property $property"
                    )
                }
            directory.resolve("${extension.binding}.kt").writeText(writer.toString())
        }
    }

    /** `val name by export()`, naming the export when its property name differs. */
    private fun declaration(artifact: String, export: String): String {
        val property = kotlinName(export)
        if (!KOTLIN_IDENTIFIER.matches(property.removeSurrounding("`")))
            throw GradleException("$artifact exports $export, which has no Kotlin property name")
        val name = if (property == export) "" else kotlinString(export)
        return "val $property by export($name)"
    }

    private companion object {
        val KOTLIN_IDENTIFIER = Regex("[A-Za-z_][A-Za-z0-9_]*")
    }
}
