package app.reseam.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.objectweb.asm.Type

private const val PROMISE = "Lcom/facebook/react/bridge/Promise;"

/**
 * Declares an extension's React Native modules for TypeScript, as `NativeModules` members typed
 * from their `@ReactMethod`s, so JavaScript calls are checked against the Kotlin signatures.
 */
internal abstract class NativeModuleTypesTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val classes: ConfigurableFileCollection

    @get:OutputDirectory abstract val output: DirectoryProperty

    @TaskAction
    fun run() {
        val outDir = output.get().asFile.also(::recreate)
        val modules =
            classes
                .classFiles()
                .map { NativeModuleScanner().scan(it) }
                .filter { it.methods.isNotEmpty() }
        if (modules.isEmpty()) return
        val out = StringBuilder()
        out.append("// Generated by the Reseam Gradle plugin from the extension's @ReactMethods.\n")
        out.append("export {};\n\n")
        out.append("declare module \"react-native\" {\n")
        out.append("    interface NativeModulesStatic {\n")
        for (module in modules.sortedBy { it.className }) {
            val name =
                module.moduleName
                    ?: throw GradleException(
                        "${module.className} has @ReactMethods but no @ReactModule(name = …)"
                    )
            out.append("        $name: {\n")
            module.methods.forEach {
                out.append("            ${signature(module.className, it)};\n")
            }
            out.append("        };\n")
        }
        out.append("    }\n}\n")
        outDir.resolve("native-modules.d.ts").writeText(out.toString())
    }

    /** A promise, which React Native passes last, becomes the method's result. */
    private fun signature(owner: String, method: NativeMethod): String {
        val where = "$owner.${method.name}"
        val promise = method.parameters.lastOrNull()?.type?.descriptor == PROMISE
        val parameters = if (promise) method.parameters.dropLast(1) else method.parameters
        parameters
            .firstOrNull { it.type.descriptor == PROMISE }
            ?.let {
                throw GradleException(
                    "$where takes a Promise as ${it.name}; React Native needs it last"
                )
            }
        if (!method.synchronous && method.returnType != Type.VOID_TYPE)
            throw GradleException(
                "$where returns ${method.returnType.className}, which React Native drops unless isBlockingSynchronousMethod"
            )
        val result =
            when {
                promise -> "Promise<unknown>"
                method.returnType == Type.VOID_TYPE -> "void"
                else -> typescript(method.returnType, method.nullableReturn, where)
            }
        val params = parameters.joinToString {
            "${it.name}: ${typescript(it.type, it.nullable, where)}"
        }
        return "${method.name}($params): $result"
    }

    private fun typescript(type: Type, nullable: Boolean, where: String): String {
        val base =
            when (type.descriptor) {
                "Z",
                "Ljava/lang/Boolean;" -> "boolean"
                "I",
                "D",
                "F",
                "Ljava/lang/Integer;",
                "Ljava/lang/Double;",
                "Ljava/lang/Float;" -> "number"
                "Ljava/lang/String;" -> "string"
                "Lcom/facebook/react/bridge/ReadableMap;",
                "Lcom/facebook/react/bridge/WritableMap;" -> "Record<string, unknown>"
                "Lcom/facebook/react/bridge/ReadableArray;",
                "Lcom/facebook/react/bridge/WritableArray;" -> "unknown[]"
                "Lcom/facebook/react/bridge/Callback;" -> "(...args: unknown[]) => void"
                "Lcom/facebook/react/bridge/Dynamic;" -> "unknown"
                else ->
                    throw GradleException(
                        "$where uses ${type.className}, which React Native cannot pass"
                    )
            }
        return if (nullable) "$base | null" else base
    }
}
