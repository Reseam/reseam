package app.reseam.gradle

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonPrimitive
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

@Serializable private data class SettingsDescription(val groups: List<GroupDescription>)

@Serializable
private data class GroupDescription(
    @SerialName("class") val className: String,
    val settings: List<SettingDescription>,
)

@Serializable
private data class SettingDescription(
    val property: String,
    val key: String,
    val valueClass: String,
    val default: JsonPrimitive,
)

/** Generates, for each settings group, the extension-side object of the same name. */
internal abstract class DeviceSettingsTask : DefaultTask() {
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val groups: RegularFileProperty

    @get:Input abstract val bundle: Property<String>

    @get:OutputDirectory abstract val output: DirectoryProperty

    @TaskAction
    fun run() {
        val outDir = output.get().asFile.also(::recreate)
        val described =
            bundleJson.decodeFromString<SettingsDescription>(groups.get().asFile.readText())
        for (group in described.groups) {
            val pkg = group.className.substringBeforeLast('.', "")
            val name = group.className.substringAfterLast('.')
            val file = outDir.resolve(pkg.replace('.', '/')).resolve("$name.kt")
            file.parentFile.mkdirs()
            file.writeText(source(pkg, name, group.settings))
        }
    }

    private fun source(pkg: String, name: String, settings: List<SettingDescription>): String {
        val writer = KotlinWriter()
        writer.line("// Generated by the Reseam Gradle plugin from the settings module.")
        if (pkg.isNotEmpty()) {
            writer.line("package $pkg")
            writer.line()
        }
        settings
            .map { it.valueClass }
            .distinct()
            .sorted()
            .forEach { writer.line("import app.reseam.runtime.$it") }
        writer.line()
        writer.block("object $name") {
            for (setting in settings) {
                val default =
                    if (setting.default.isString) kotlinString(setting.default.content)
                    else setting.default.content
                line(
                    "@JvmField val ${setting.property} = ${setting.valueClass}(" +
                        "${kotlinString(bundle.get())}, ${kotlinString(setting.key)}, $default)"
                )
            }
        }
        return writer.toString()
    }
}
