package app.reseam.gradle

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

@Serializable private data class SettingsDescription(val groups: List<GroupDescription>)

@Serializable
private data class GroupDescription(
    @SerialName("class") val className: String,
    val settings: List<SettingDescription>,
)

@Serializable
private data class SettingDescription(
    val property: String,
    val key: String,
    val valueClass: String,
    val default: JsonElement,
    val mimeTypes: List<String>? = null,
)

/** Generates, for each settings group, the extension-side object of the same name. */
internal abstract class DeviceSettingsTask : DefaultTask() {
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val groups: RegularFileProperty

    @get:Input abstract val bundle: Property<String>

    @get:OutputDirectory abstract val output: DirectoryProperty

    @TaskAction
    fun run() {
        val outDir = output.get().asFile.also(::recreate)
        val described =
            bundleJson.decodeFromString<SettingsDescription>(groups.get().asFile.readText())
        for (group in described.groups) {
            val pkg = group.className.substringBeforeLast('.', "")
            val name = group.className.substringAfterLast('.')
            val file = outDir.resolve(pkg.replace('.', '/')).resolve("$name.kt")
            file.parentFile.mkdirs()
            file.writeText(source(pkg, name, group.settings))
        }
    }

    private fun source(pkg: String, name: String, settings: List<SettingDescription>): String {
        val writer = KotlinWriter()
        writer.line("// Generated by the Reseam Gradle plugin from the settings module.")
        if (pkg.isNotEmpty()) {
            writer.line("package $pkg")
            writer.line()
        }
        settings
            .map { it.valueClass }
            .distinct()
            .sorted()
            .forEach { writer.line("import app.reseam.runtime.$it") }
        writer.line()
        writer.block("object $name") {
            for (setting in settings) {
                val arguments =
                    listOf(kotlinString(bundle.get()), kotlinString(setting.key)) +
                        defaultArguments(setting) +
                        listOfNotNull(
                            setting.mimeTypes?.joinToString(prefix = "listOf(", postfix = ")") {
                                kotlinString(it)
                            }
                        )
                line(
                    "@JvmField val ${setting.property} = " +
                        "${setting.valueClass}(${arguments.joinToString(", ")})"
                )
            }
        }
        return writer.toString()
    }
}

private fun defaultArguments(setting: SettingDescription): List<String> =
    when (setting.valueClass) {
        "NumberValue" -> listOf(decimal(setting.default.jsonPrimitive))
        "RangeValue" ->
            setting.default.jsonObject.let {
                listOf(
                    decimal(it.getValue("start").jsonPrimitive),
                    decimal(it.getValue("end").jsonPrimitive),
                )
            }
        "ColorValue" ->
            listOf("0x%08X.toInt()".format(setting.default.jsonPrimitive.content.toLong()))
        else ->
            setting.default.jsonPrimitive.let {
                listOf(if (it.isString) kotlinString(it.content) else it.content)
            }
    }

private fun decimal(number: JsonPrimitive) = number.content.toDouble().toString()
