package app.reseam.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.objectweb.asm.Type

internal const val EXPORT = "Lapp/reseam/runtime/Export;"
private val EXT_CLASS_MEMBERS =
    setOf("descriptor", "target", "static", "method", "field", "toString")

internal enum class ExportKind(val delegate: String) {
    STATIC("static"),
    METHOD("method"),
    FIELD("field"),
}

/** [name] is the binding's; [member] the JVM member's. */
internal data class ExportedMember(
    val name: String,
    val member: String,
    val kind: ExportKind,
    val descriptor: String,
)

/**
 * Generates an `ExtClass` binding for every extension class with `@Export` on it or its members.
 */
internal abstract class ExportBindingsTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val classes: ConfigurableFileCollection

    @get:OutputDirectory abstract val output: DirectoryProperty

    @TaskAction
    fun run() {
        val outDir = output.get().asFile.also(::recreate)
        val scanned =
            classes
                .classFiles()
                .map { ExportScanner().scan(it) }
                .filter { it.exported || it.members.isNotEmpty() }
                .associateBy { it.name }
        val names = scanned.keys.flatMap(::withOuterClasses).toSet()
        val nested = names.filter { '$' in it }.groupBy { it.substringBeforeLast('$') }
        for (name in names.filter { '$' !in it }) {
            val pkg = name.substringBeforeLast('/', "").replace('/', '.')
            val file =
                outDir.resolve(
                    "${name.substringBeforeLast('/', "")}/bindings/${name.substringAfterLast('/')}.kt"
                )
            file.parentFile.mkdirs()
            val writer = KotlinWriter()
            writer.line("// Generated by the Reseam Gradle plugin from @Export declarations.")
            writer.line("package ${if (pkg.isEmpty()) "" else "$pkg."}bindings")
            writer.line()
            writer.line("import app.reseam.patch.ExtClass")
            writer.line()
            writer.binding(name, scanned, nested)
            file.writeText(writer.toString())
        }
    }

    private fun withOuterClasses(name: String): List<String> =
        name.indices.filter { name[it] == '$' }.map { name.substring(0, it) } + name

    private fun KotlinWriter.binding(
        name: String,
        scanned: Map<String, ExportScanner>,
        nested: Map<String, List<String>>,
    ) {
        val members = scanned[name]?.members.orEmpty()
        for ((member, overloads) in members.groupBy { it.name }) {
            if (overloads.size > 1)
                throw GradleException(
                    "$name exports $member twice; name the overloads with @Export(name = …)"
                )
            if (member in EXT_CLASS_MEMBERS)
                throw GradleException("$name exports $member, a name ExtClass uses")
        }
        val simple = name.substringAfterLast('/').substringAfterLast('$')
        block("object ${kotlinName(simple)} : ExtClass(${kotlinString(name.replace('/', '.'))})") {
            members.forEach { line(declaration(it)) }
            nested[name].orEmpty().forEach {
                line()
                binding(it, scanned, nested)
            }
        }
    }

    private fun declaration(member: ExportedMember): String {
        val arguments =
            if (member.kind == ExportKind.FIELD) listOf(kotlinString(member.descriptor))
            else
                Type.getArgumentTypes(member.descriptor).map { kotlinString(it.descriptor) } +
                    listOfNotNull(
                        Type.getReturnType(member.descriptor)
                            .descriptor
                            .takeIf { it != "V" }
                            ?.let {
                                "returns = ${kotlinString(it)}"
                            }
                    )
        val jvmName =
            if (member.member == member.name) emptyList()
            else listOf("name = ${kotlinString(member.member)}")
        return "val ${kotlinName(member.name)} by ${member.kind.delegate}(${(arguments + jvmName).joinToString()})"
    }
}
