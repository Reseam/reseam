package app.reseam.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity

/** A task that generates a Kotlin object from the `strings.xml` files in `src/main/strings`. */
internal abstract class StringObjectTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: DirectoryProperty

    /** The generated object, such as `app.example.settings.ExampleStrings`. */
    @get:Input abstract val objectName: Property<String>

    protected fun readStrings(): List<StringFile> {
        val files = readStringFiles(sources.get().asFile)
        val names = files.single { it.locale == DEFAULT_LOCALE }.strings.keys.map(::kotlinName)
        if (names.toSet().size != names.size || names.any { it in RESERVED_NAMES })
            throw GradleException(
                "${sources.get()}: string names must map to distinct Kotlin names other than $RESERVED_NAMES"
            )
        return files
    }

    protected fun writeObject(directory: DirectoryProperty, body: KotlinWriter.() -> Unit) {
        val pkg = objectName.get().substringBeforeLast('.', "")
        val file =
            directory
                .get()
                .asFile
                .also(::recreate)
                .resolve(pkg.replace('.', '/'))
                .resolve("${simpleName()}.kt")
        file.parentFile.mkdirs()
        file.writeText(
            KotlinWriter()
                .apply {
                    line("// Generated by the Reseam Gradle plugin from src/main/strings.")
                    if (pkg.isNotEmpty()) {
                        line("package $pkg")
                        line()
                    }
                    body()
                }
                .toString()
        )
    }

    protected fun simpleName() = objectName.get().substringAfterLast('.')
}
