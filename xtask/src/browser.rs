use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, ensure};
use serde::Serialize;
use sha2::{Digest, Sha256};

use crate::{paths, run};

const TARGET: &str = "wasm32-wasip1";

#[derive(Serialize)]
struct Asset {
    path: &'static str,
    sha256: String,
    size: u64,
}

/// What `src/runtime.generated.ts` exports: the content-addressed asset directory the loader verifies.
#[derive(Serialize)]
struct Runtime {
    base: String,
    assets: BTreeMap<&'static str, Asset>,
}

/// Builds the browser engine, compression worker, Java host and patch runtime, and publishes
/// them under `browser/public/runtime/<hash>/` with their sums in `src/runtime.generated.ts`.
pub fn pack() -> Result<()> {
    let wasi_sdk = PathBuf::from(
        env::var_os("WASI_SDK_PATH")
            .context("set WASI_SDK_PATH to the extracted WASI SDK 33 directory")?,
    );
    let clang = wasi_sdk.join("bin/clang");
    ensure!(
        clang.is_file(),
        "WASI SDK clang was not found in {}",
        wasi_sdk.join("bin").display()
    );
    let root = paths::workspace_root();
    run::run(Command::new("rustup").args(["target", "add", TARGET]))?;
    crate::patch_api::regen()?;
    crate::runtime()?;
    run::run(
        Command::new("cargo")
            .args(["build", "--locked", "--profile=browser", "--target", TARGET])
            .args([
                "--package=reseam-sdk-browser",
                "--package=reseam-browser-compression",
            ])
            .env("CC_wasm32_wasip1", clang)
            .env("AR_wasm32_wasip1", wasi_sdk.join("bin/llvm-ar"))
            .current_dir(&root),
    )?;
    run::gradle(&[
        ":reseam-browser-host:hostJar",
        ":reseam-browser-host:browserRuntimeJar",
    ])?;
    let wasm = paths::target_dir().join(TARGET).join("browser");
    let jars = root.join("browser/build/runtime");
    let sources: [(&'static str, PathBuf); 5] = [
        (
            "reseam_sdk_browser.wasm",
            wasm.join("reseam_sdk_browser.wasm"),
        ),
        (
            "reseam_browser_compression.wasm",
            wasm.join("reseam_browser_compression.wasm"),
        ),
        (
            "methods.json",
            root.join("patch-api/generated/browser/methods.json"),
        ),
        ("reseam-runtime.jar", jars.join("reseam-runtime.jar")),
        ("browser-host.jar", jars.join("browser-host.jar")),
    ];
    publish(&root.join("browser"), &sources)
}

fn publish(browser: &Path, sources: &[(&'static str, PathBuf)]) -> Result<()> {
    let assets = sources
        .iter()
        .map(|(path, source)| {
            let bytes =
                fs::read(source).with_context(|| format!("reading {}", source.display()))?;
            let asset = Asset {
                path,
                sha256: hex::encode(Sha256::digest(&bytes)),
                size: bytes.len() as u64,
            };
            Ok((*path, asset))
        })
        .collect::<Result<BTreeMap<_, _>>>()?;
    let release = hex::encode(Sha256::digest(serde_json::to_vec(&assets)?));
    let release = &release[..20];
    let public = browser.join("public/runtime");
    if public.exists() {
        fs::remove_dir_all(&public)?;
    }
    let directory = public.join(release);
    fs::create_dir_all(&directory)?;
    for (path, source) in sources {
        fs::copy(source, directory.join(path))?;
    }
    let runtime = Runtime {
        base: format!("runtime/{release}/"),
        assets,
    };
    fs::write(
        browser.join("src/runtime.generated.ts"),
        format!(
            "// Generated by `cargo xtask pack-browser`. Do not edit.\nexport const runtime = {} as const;\n",
            serde_json::to_string_pretty(&runtime)?
        ),
    )?;
    writeln!(std::io::stdout(), "Packaged browser runtime {release}")?;
    Ok(())
}
